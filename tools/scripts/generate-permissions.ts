/**
 * Regenerates libs/models/src/lib/permission-keys.generated.ts from the live
 * permission catalogue (`GET /v1/admin/permissions`), so permission keys used in
 * code are checked at compile time instead of typed by hand.
 *
 * Get a token by signing in to the admin audience without `X-Client: web`
 * (the API then returns the pair in the body):
 *
 *   curl -s localhost:3000/v1/auth/login -H 'content-type: application/json' \
 *     -d '{"method":"PASSWORD","email":"…","password":"…","audience":"ADMIN",
 *          "device":{"platform":"WEB","name":"permissions script"}}' | jq -r .data.tokens.accessToken
 *
 *   ADMIN_ACCESS_TOKEN=<token> yarn generate:permissions
 *   API_BASE_URL=https://api.staging.example yarn generate:permissions   # optional
 *
 * Commit the diff. Run it whenever grov-be adds, renames or removes a permission.
 */
import {writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

interface Permission {
  key: string;
  name: string;
  description: string;
}
interface PermissionGroup {
  module: string;
  label: string;
  permissions: Permission[];
}

const OUTPUT = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../../libs/models/src/lib/permission-keys.generated.ts'
);

const constCase = (value: string): string =>
  value
    .replace(/[^a-zA-Z0-9]+/g, '_')
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/^_+|_+$/g, '')
    .toUpperCase();

async function fetchCatalogue(): Promise<PermissionGroup[]> {
  const token = process.env.ADMIN_ACCESS_TOKEN;
  if (!token) throw new Error('Set ADMIN_ACCESS_TOKEN (see the comment at the top of this file).');
  const base = (process.env.API_BASE_URL ?? 'http://localhost:3000').replace(/\/+$/, '');
  const response = await fetch(`${base}/v1/admin/permissions`, {
    headers: {Accept: 'application/json', Authorization: `Bearer ${token}`},
  });
  const body = (await response.json()) as {
    status: boolean;
    data?: PermissionGroup[];
    code?: string;
  };
  if (!response.ok || !body.status || !Array.isArray(body.data)) {
    throw new Error(`GET /v1/admin/permissions failed: ${response.status} ${body.code ?? ''}`);
  }
  return body.data;
}

function render(groups: PermissionGroup[]): string {
  const keys: string[] = [];
  const blocks = groups.map(group => {
    const lines = group.permissions.map(p => {
      keys.push(p.key);
      const member = constCase(p.key.split('.').slice(1).join('_'));
      return `    /** ${p.name}: ${p.description} */\n    ${member}: '${p.key}',`;
    });
    return `  ${constCase(group.module)}: {\n${lines.join('\n')}\n  },`;
  });
  return `// AUTO-GENERATED by \`yarn generate:permissions\` from GET /v1/admin/permissions. Do not edit.

export const PERMISSIONS = {
${blocks.join('\n')}
} as const;

export type PermissionKey =
${[...new Set(keys)]
  .sort()
  .map(k => `  | '${k}'`)
  .join('\n')};
`;
}

fetchCatalogue()
  .then(groups => {
    writeFileSync(OUTPUT, render(groups));
    const total = groups.reduce((sum, g) => sum + g.permissions.length, 0);
    console.log(`Wrote ${total} permissions in ${groups.length} groups to ${OUTPUT}`);
  })
  .catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
